#!/usr/bin/env python3
"""Build reports/manifest.js, the document index used by the Reports page.

A static web page cannot list a folder by itself, so run this script every
time PDFs are added, renamed or removed:

    python tools/build_reports_manifest.py

(or double-click tools/build_reports_manifest.bat on Windows), then press
Refresh on the Reports page.

Folder layout - one sub-folder per project, named after the project slug
(lower-case, spaces become "-"):

    reports/
        website-redesign/      <- project "Website Redesign"
            Kickoff Meeting Minutes.pdf
        mobile-app-v2/         <- project "Mobile App v2"
            Project Scope v1.pdf

Only top-level *.pdf files inside each project folder are indexed.
"""
import datetime
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
REPORTS = ROOT / 'reports'


def main() -> None:
    REPORTS.mkdir(exist_ok=True)
    folders = []
    for folder in sorted((p for p in REPORTS.iterdir() if p.is_dir()), key=lambda p: p.name.lower()):
        files = []
        for f in sorted((x for x in folder.iterdir() if x.is_file() and x.suffix.lower() == '.pdf'),
                        key=lambda x: x.name.lower()):
            st = f.stat()
            files.append({
                'name': f.name,
                'path': f.relative_to(ROOT).as_posix(),
                'size': st.st_size,
                'modified': datetime.datetime.fromtimestamp(st.st_mtime).isoformat(timespec='seconds'),
            })
        folders.append({'folder': folder.name, 'files': files})

    data = {'generated': datetime.datetime.now().isoformat(timespec='seconds'), 'folders': folders}
    out = REPORTS / 'manifest.js'
    out.write_text(
        '// Generated by tools/build_reports_manifest.py - do not edit by hand.\n'
        'window.REPORTS_MANIFEST = ' + json.dumps(data, ensure_ascii=False, indent=2) + ';\n',
        encoding='utf-8')
    total = sum(len(f['files']) for f in folders)
    print(f'Wrote {out.relative_to(ROOT)}: {total} PDF(s) in {len(folders)} folder(s)')


if __name__ == '__main__':
    main()
